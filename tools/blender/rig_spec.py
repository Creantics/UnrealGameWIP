        ("neck_02", "neck_01", (0.0, -0.005, 1.52), (0.0, -0.01, 1.58), X, "core", True),
        ("head", "neck_02", (0.0, -0.01, 1.58), (0.0, -0.01, 1.78), X, "core", True),
        ("jaw", "head", (0.0, 0.005, 1.66), (0.0, -0.085, 1.60), X, "face", True),
        ("tongue_01", "jaw", (0.0, -0.02, 1.630), (0.0, -0.045, 1.628), X, "face", True),
        ("tongue_02", "tongue_01", (0.0, -0.045, 1.628), (0.0, -0.065, 1.629), X, "face", True),
