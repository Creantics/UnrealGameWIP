def expand_pose(pose):
    """{base name: (x, y, z) deg} -> {joint: (x, y, z) deg}, sided bases applied to both sides (mirrored)."""
    out = {}
    for base, (x, y, z) in pose.items():
        if base + "_l" in JOINT_NAMES:
            out[base + "_l"] = (x, y, z)
            out[base + "_r"] = (x, -y, -z)
        else:
            assert base in JOINT_NAMES, base
            out[base] = (x, y, z)
    return out


