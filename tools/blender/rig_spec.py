def mirror_name(n):
    if n.endswith("_l"):
        return n[:-2] + "_r"
    if n.endswith("_r"):
        return n[:-2] + "_l"
    return n


def order_hash(names=None):
    """sha1 over 'name:parent' lines in joint order (R12)."""
    parents = {r[0]: r[1] or "" for r in JOINTS}
    names = names or JOINT_NAMES
    s = "\n".join("%s:%s" % (n, parents.get(n, "?")) for n in names)
    return hashlib.sha1(s.encode()).hexdigest()


