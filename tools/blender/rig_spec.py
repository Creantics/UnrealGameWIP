"""The canonical humanoid skeleton (docs/rigging_plan.md §4) as plain data. No bpy: the validator, the
fitter and the tests all read the same tables. `make_rig_template.py` writes them to
assets/rig/canonical_humanoid.json, which is the file other tools load.

Coordinates are Blender's (metres, X = character left, -Y = facing direction, Z up, soles at z = 0).
Each joint has a head, a tail and an `x_axis` hint: the bone roll is set so that the bone's local +X is
as close as possible to the hint, which makes flexion a positive rotation about local +X on every hinge
(§4.2). Right-side joints are the mirror of the left (x -> -x); their X hint is -S(x_left) with
S = diag(-1, 1, 1), Blender's own mirror convention, so the same local rotation flexes both sides.
"""
import hashlib
import json
import math

VERSION = 1
HEIGHT_M = 1.80  # reference height of the template (the proof head and mannequin are built to it)

# Face anchors shared with the proof head (make_rig_template.build_proof_head).
HEAD_CENTER = (0.0, -0.01, 1.69)
HEAD_RADII = (0.078, 0.098, 0.118)  # x (half width), y (half depth), z (half height)
MOUTH_Z = 1.635
EYE_X, EYE_Z, EYE_R = 0.032, 1.705, 0.012


def _ellipsoid_front_y(x, z):
    cx, cy, cz = HEAD_CENTER
    rx, ry, rz = HEAD_RADII
    t = 1.0 - ((x - cx) / rx) ** 2 - ((z - cz) / rz) ** 2
    return cy - ry * math.sqrt(max(t, 0.0))


EYE_Y = _ellipsoid_front_y(EYE_X, EYE_Z) + EYE_R - 0.005  # the eyeball pokes 5 mm out of the skull

# ------------------------------------------------------------------------------------------------
# Joint table. (name, parent, head, tail, x_axis hint, group, deform)
# Defined for the centre line and the left side; the right side is generated by mirroring.
# ------------------------------------------------------------------------------------------------


def _add(a, b, s=1.0):
    return tuple(a[i] + b[i] * s for i in range(3))


def _norm(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _left_side():
    J = []
    X = (1.0, 0.0, 0.0)
    # Arm. A-pose: upper arm 45 deg below horizontal, elbow bent 10 deg forward.
    sh = (0.175, 0.01, 1.42)
    d1 = _norm((1.0, 0.0, -1.0))
    elbow = _add(sh, d1, 0.28)
    c10, s10 = math.cos(math.radians(10)), math.sin(math.radians(10))
    d2 = _norm(_add(tuple(c * c10 for c in d1), (0.0, -1.0, 0.0), s10))
    wrist = _add(elbow, d2, 0.26)
    arm_x = _norm(_cross(d1, (0.0, -1.0, 0.0)))  # elbow flexion axis (moves the forearm forward)
    arm_x = tuple(-c for c in arm_x) if _cross(arm_x, d1)[1] > 0 else arm_x
    J += [
        ("clavicle", "spine_03", (0.025, -0.02, 1.42), sh, (0.0, -1.0, 0.0), "arm", True),
        ("upperarm", "clavicle", sh, elbow, arm_x, "arm", True),
        ("upperarm_twist_01", "upperarm", _add(sh, d1, 0.28 / 3), _add(sh, d1, 0.28 / 3 + 0.05), arm_x, "arm", True),
        ("upperarm_twist_02", "upperarm", _add(sh, d1, 0.56 / 3), _add(sh, d1, 0.56 / 3 + 0.05), arm_x, "arm", True),
        ("lowerarm", "upperarm", elbow, wrist, arm_x, "arm", True),
        ("lowerarm_twist_01", "lowerarm", _add(elbow, d2, 0.26 / 3), _add(elbow, d2, 0.26 / 3 + 0.05), arm_x, "arm",
         True),
        ("lowerarm_twist_02", "lowerarm", _add(elbow, d2, 0.52 / 3), _add(elbow, d2, 0.52 / 3 + 0.05), arm_x, "arm",
         True),
        ("hand", "lowerarm", wrist, _add(wrist, d2, 0.08), arm_x, "arm", True),
    ]
    # Hand: fingers along d2, spread across the width axis w (forward-ish), palm normal n.
    # Palm faces down/in (along the elbow axis in the A-pose); fingers curl toward it, so the finger
    # flexion axis fx = d2 x n, which is also the width axis of the palm (+fx = backward).
    n = _norm(_add(arm_x, d2, -sum(arm_x[i] * d2[i] for i in range(3))))
    fx = _norm(_cross(d2, n))
    w = fx
    fingers = [("index", 0.025, (0.045, 0.027, 0.022), False), ("middle", 0.005, (0.05, 0.03, 0.023), False),
               ("ring", -0.014, (0.046, 0.028, 0.022), True), ("pinky", -0.032, (0.036, 0.022, 0.019), True)]
    for name, off, lens, meta in fingers:
        knuckle = _add(_add(wrist, d2, 0.095), w, -off)
        parent = "hand"
        if meta:
            base = _add(_add(wrist, d2, 0.02), w, -off * 0.6)
            J.append((name + "_00", "hand", base, knuckle, fx, "hand", True))
            parent = name + "_00"
        p = knuckle
        for i, ln in enumerate(lens):
            q = _add(p, d2, ln)
            J.append(("%s_%02d" % (name, i + 1), parent, p, q, fx, "hand", True))
            parent, p = "%s_%02d" % (name, i + 1), q
    t = _norm(_add(_add(tuple(c * 0.6 for c in d2), w, -0.6), n, 0.4))
    p, parent = _add(_add(wrist, d2, 0.025), w, -0.025), "hand"
    tx = _norm(_cross(t, n))
    for i, ln in enumerate((0.04, 0.032, 0.027)):
        q = _add(p, t, ln)
        J.append(("thumb_%02d" % (i + 1), parent, p, q, tx, "hand", True))
        parent, p = "thumb_%02d" % (i + 1), q
    # Leg. Twist bones are children of the segment they twist (siblings of the next segment).
    hip, knee, ankle = (0.09, 0.0, 0.94), (0.095, -0.005, 0.52), (0.10, 0.02, 0.09)
    ball, toe = (0.105, -0.11, 0.02), (0.105, -0.17, 0.02)
    J += [
        ("thigh", "pelvis", hip, knee, X, "leg", True),
        ("thigh_twist_01", "thigh", _add(hip, _norm(_add(knee, hip, -1)), 0.21),
         _add(hip, _norm(_add(knee, hip, -1)), 0.26), X, "leg", True),
        ("calf", "thigh", knee, ankle, X, "leg", True),
        ("calf_twist_01", "calf", _add(knee, _norm(_add(ankle, knee, -1)), 0.215),
         _add(knee, _norm(_add(ankle, knee, -1)), 0.265), X, "leg", True),
        ("foot", "calf", ankle, ball, X, "leg", True),
        ("ball", "foot", ball, toe, X, "leg", True),
    ]
    # Helpers (volume keepers; driven by joint rules, §11).
    J += [
        ("elbow_helper", "lowerarm", elbow, _add(elbow, _norm(_cross(arm_x, d1)), -0.04), arm_x, "helper", True),
        ("knee_helper", "calf", knee, _add(knee, (0, -1, 0), 0.04), X, "helper", True),
        ("deltoid_helper", "upperarm", _add(sh, d1, 0.04), _add(_add(sh, d1, 0.04), (0, 0, 1), 0.04), arm_x,
         "helper", True),
        ("glute_helper", "pelvis", (0.08, 0.06, 0.9), (0.08, 0.10, 0.9), X, "helper", True),
    ]
    J.append(("weapon", "hand", _add(_add(wrist, d2, 0.07), n, 0.03), _add(_add(wrist, d2, 0.07), n, 0.03 + 0.06),
              fx, "socket", True))
    return J


def _mirror_pt(p):
    return (-p[0], p[1], p[2])


def _mirror_axis(a):
    return (a[0], -a[1], -a[2])  # -S a with S = diag(-1, 1, 1)


